import type { CountryCode } from '../types/country';
import type { CanonicalTrackId, TrackScoreBreakdown } from '../types/track';
import { canonicalTrackId, calculateTrackScore } from '../types/track';

export type CountryId = CountryCode;

export interface TrackCountryScore {
  compositeScore: number;
  status: 'loose' | 'moderate' | 'tight';
  tier: 'GREEN' | 'YELLOW' | 'RED';
  tierLabel: string;
  dimensions: {
    policy: number;      // 政策友好度 (35%)
    prCertainty: number; // 永居确定性 (30%)
    jobMarket: number;   // 就业薪资 (25%)
    lowFriction: number; // 低门槛指数 (10%)
  };
  headline: string;
  verdict: string;
  fatalBottlenecks: string[];
  recommendedVisas: {
    id: string;
    code: string;
    name: string;
    highlight: string;
  }[];
  humorTip?: string;
}

function createScore(
  policy: number,
  pr: number,
  job: number,
  barrier: number,
  headline: string,
  verdict: string,
  fatalBottlenecks: string[],
  recommendedVisas: { id: string; code: string; name: string; highlight: string }[],
  humorTip?: string
): TrackCountryScore {
  const scores: TrackScoreBreakdown = calculateTrackScore(policy, pr, job, barrier);
  let status: 'loose' | 'moderate' | 'tight' = 'moderate';
  if (scores.tier === 'GREEN') status = 'loose';
  else if (scores.tier === 'RED') status = 'tight';

  return {
    compositeScore: scores.compositeScore,
    status,
    tier: scores.tier,
    tierLabel: scores.tierLabel,
    dimensions: {
      policy,
      prCertainty: pr,
      jobMarket: job,
      lowFriction: barrier,
    },
    headline,
    verdict,
    fatalBottlenecks,
    recommendedVisas,
    humorTip,
  };
}

