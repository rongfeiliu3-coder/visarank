// Helper: 获取指定专业在指定国家的准确打分
export function getTrackCountryScore(trackId?: string, countryCode?: CountryCode): TrackCountryScore {
  const canonicalId = canonicalTrackId(trackId);
  const code = (countryCode || 'NZ') as CountryCode;
  const trackMap = TRACK_COUNTRY_MATRIX[canonicalId] || TRACK_COUNTRY_MATRIX.cs_ai;
  return trackMap[code] || trackMap.NZ || TRACK_COUNTRY_MATRIX.cs_ai.NZ;
}

// 兼容旧版 COUNTRY_RANKINGS 矩阵导出
export interface CountryTrackScoreMatrix {
  countryCode: CountryCode;
  averageCompositeScore: number;
  trackBreakdown: Record<CanonicalTrackId, TrackCountryScore>;
}

export const COUNTRY_RANKINGS: Record<CountryCode, CountryTrackScoreMatrix> = ((): Record<
  CountryCode,
  CountryTrackScoreMatrix
> => {
  const result: Partial<Record<CountryCode, CountryTrackScoreMatrix>> = {};
  const countryCodes: CountryCode[] = [
    'NZ', 'AU', 'CA', 'DE', 'UK', 'IE', 'JP', 'SG', 'US', 'NL', 'FR', 'SE', 'DK', 'FI'
  ];

  for (const ccode of countryCodes) {
    const trackBreakdown: Partial<Record<CanonicalTrackId, TrackCountryScore>> = {};
    let totalScore = 0;
    let count = 0;

    for (const [tId, tMap] of Object.entries(TRACK_COUNTRY_MATRIX)) {
      const score = tMap[ccode];
      if (score) {
        trackBreakdown[tId as CanonicalTrackId] = score;
        totalScore += score.compositeScore;
        count += 1;
      }
    }

    result[ccode] = {
      countryCode: ccode,
      averageCompositeScore: count > 0 ? Number((totalScore / count).toFixed(1)) : 7.5,
      trackBreakdown: trackBreakdown as Record<CanonicalTrackId, TrackCountryScore>,
    };
  }

  return result as Record<CountryCode, CountryTrackScoreMatrix>;
})();
